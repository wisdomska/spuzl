/**
 * Builds the family-safe validation list (en.data.ts) from SCOWL / ESDB size 50 (US + GB ise), which is
 * published under a permissive licence (see LICENSE.md in this folder).
 *
 *   pnpm tsx games/_shared/words/build.ts [path-to-scowl-wordlist.txt]
 *
 * Without a path it downloads the list from app.aspell.net. Keeps lowercase a to z words of 3 to 15
 * letters, drops every blocklisted word and its common inflections (blocklist.rot13.txt, ROT13 so the
 * repo does not carry the words in plain text), adds EXTRA_WORDS, then prefix-packs the sorted list.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { EXTRA_WORDS } from "./extra";
import { pack } from "./pack";

const SRC =
  "http://app.aspell.net/create?max_size=50&spelling=US&spelling=GBs&max_variant=0&diacritic=strip&special=hacker&download=wordlist&encoding=utf-8&format=inline";
const here = path.dirname(new URL(import.meta.url).pathname);

const rot13 = (s: string) => s.replace(/[a-z]/g, (c) => String.fromCharCode(((c.charCodeAt(0) - 97 + 13) % 26) + 97));
const SUFFIXES = ["", "s", "es", "ed", "ing", "er", "ers", "y", "ies", "ly", "ish", "iest", "ier"];
/** Roots that also block any word containing them (only unambiguous ones). */
const CONTAINS = ["shvx", "fuvg", "phag", "avtt", "snttb", "jubar", "cbea", "qvyqb", "crqbcuvy", "znfgheong"].map(rot13);

/** Everyday words a prefix rule would wrongly catch. */
const ALLOW = new Set([
  "butter",
  "butters",
  "buttered",
  "buttering",
  "buttery",
  "spicy",
  "spicier",
  "spiciest",
  "prickly",
  "pricklier",
  "prickliest",
  "bonkers",
  "hellos",
]);

export function blocked(word: string, block: Set<string>): boolean {
  if (ALLOW.has(word)) return false;
  if (CONTAINS.some((c) => word.includes(c))) return true;
  for (const b of block) {
    if (!word.startsWith(b)) continue;
    const rest = word.slice(b.length);
    if (SUFFIXES.includes(rest)) return true;
    // doubled final consonant: "x" + "xed"
    if (rest.length > 1 && rest[0] === b[b.length - 1] && SUFFIXES.includes(rest.slice(1))) return true;
  }
  return false;
}

async function main() {
  const arg = process.argv[2];
  const raw = arg ? readFileSync(arg, "utf8") : await (await fetch(SRC)).text();
  const body = raw.slice(raw.indexOf("\n---") + 4);
  const block = new Set(
    readFileSync(path.join(here, "blocklist.rot13.txt"), "utf8")
      .split("\n")
      .map((w) => rot13(w.trim()))
      .filter(Boolean),
  );
  const out = new Set<string>();
  for (const line of body.split("\n")) {
    const w = line.trim();
    if (!/^[a-z]{3,15}$/.test(w)) continue;
    if (blocked(w, block)) continue;
    out.add(w);
  }
  for (const w of EXTRA_WORDS) out.add(w);
  const words = [...out].sort();
  const packed = pack(words);
  const file = `/* Generated by build.ts from SCOWL / ESDB size 50 (see LICENSE.md). Do not edit by hand. ${words.length} words. */\nexport const PACKED = ${JSON.stringify(packed)};\n`;
  writeFileSync(path.join(here, "en.data.ts"), file);
  console.log(`wrote ${words.length} words, ${packed.length} chars`);
}

if (process.argv[1] && process.argv[1].endsWith("build.ts")) void main();
