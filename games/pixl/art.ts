export function artCells(a: Art): { w: number; h: number; cells: number[] } {
  const h = a.rows.length,
    w = a.rows[0].length;
  return { w, h, cells: a.rows.flatMap((r) => [...r].map((ch) => (ch === "#" ? 1 : 0))) };
}
