// Builds components/ui/icons.generated.ts: Phosphor *Bold* icons as raw SVG markup, keyed by kebab-case name.
// Only the bold weight ships (the design uses Phosphor Bold everywhere), as one small string per icon,
// instead of the barrel import, which pulled every weight of every icon into the shared bundle.
// Usage: node scripts/gen-icons.mjs [extra-icon-names...]   (keeps the names already in the registry)
import fs from "node:fs";
import path from "node:path";

const OUT = "components/ui/icons.generated.ts";
const DEFS = "node_modules/@phosphor-icons/react/dist/defs";
const pascal = (n) =>
  n
    .split("-")
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
const kebab = (n) =>
  n
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
const names = new Set([
  ...[...current.matchAll(/^\s+"?([a-z0-9-]+)"?: /gm)].map((m) => m[1]),
  ...[...current.matchAll(/^\s+([A-Z][A-Za-z0-9]+),$/gm)].map((m) => kebab(m[1])),
  ...process.argv.slice(2),
]);

const attrName = (k) =>
  ({
    strokeLinecap: "stroke-linecap",
    strokeLinejoin: "stroke-linejoin",
    strokeWidth: "stroke-width",
    fillRule: "fill-rule",
    clipRule: "clip-rule",
    strokeMiterlimit: "stroke-miterlimit",
  })[k] ?? k;

function boldMarkup(file) {
  const src = fs.readFileSync(file, "utf8");
  const start = src.indexOf('"bold"');
  if (start < 0) return null;
  const next = src.indexOf('\n  [\n    "', start + 6);
  const block = src.slice(start, next < 0 ? undefined : next);
  const out = [];
  for (const m of block.matchAll(/createElement\(\s*"([a-z]+)",\s*\{([^}]*)\}\s*\)/g)) {
    const attrs = [...m[2].matchAll(/([A-Za-z]+):\s*("([^"]*)"|[0-9.]+)/g)].map((a) => `${attrName(a[1])}="${a[3] ?? a[2]}"`);
    out.push(`<${m[1]} ${attrs.join(" ")}/>`);
  }
  return out.join("");
}

const entries = [];
const missing = [];
for (const n of [...names].sort()) {
  const file = path.join(DEFS, `${pascal(n)}.es.js`);
  if (!fs.existsSync(file)) {
    missing.push(n);
    continue;
  }
  const svg = boldMarkup(file);
  if (!svg) {
    missing.push(n);
    continue;
  }
  entries.push([n, svg]);
}
const body = [
  "/* Generated by scripts/gen-icons.mjs: Phosphor Bold icons used by SPUZL as inner SVG markup (viewBox 0 0 256 256),",
  "   keyed by kebab-case name (the design writes them as ph-<name>). Do not edit by hand; add names to the script call. */",
  "export const ICONS: Record<string, string> = {",
  ...entries.map(([n, s]) => `  ${JSON.stringify(n)}: ${JSON.stringify(s)},`),
  "};",
  "",
].join("\n");
fs.writeFileSync(OUT, body);
console.log(
  `${entries.length} icons, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB raw`,
  missing.length ? `missing: ${missing.join(" ")}` : "",
);
