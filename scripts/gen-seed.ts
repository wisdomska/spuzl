/**
 * Writes supabase/seed.sql from the TypeScript sources of truth (catalogue, badges, quests, cosmetics),
 * so the database and the app never disagree. Run: pnpm tsx scripts/gen-seed.ts
 */
import fs from "node:fs";
import { ALL_WORLDS, GAMES, LAB_GAMES, RETIRED_GAMES, WORLDS, type GameMeta } from "../lib/catalog";
import { BADGES } from "../lib/gamification/badges";
import { DAILY_POOL, WEEKLY_CHAIN } from "../lib/gamification/quests";
import { COSMETICS } from "../lib/gamification/cosmetics";

const q = (s: string | null | undefined) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const out: string[] = ["-- Generated by scripts/gen-seed.ts. Do not edit by hand.", "begin;"];

// Every world, empty ones too: retired games keep their world row (foreign key), the app hides empty worlds.
out.push("insert into public.worlds (id, name, sort) values");
out.push(
  ALL_WORLDS.map((w, i) => `  (${q(w.id)}, ${q(w.name)}, ${i})`).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, sort = excluded.sort;",
);

// Live games, then retired ones (lib/catalog RETIRED_IDS: hidden from players, refused by the server; migration
// 20261116000001). Both carry their status, so a fresh database matches the catalog.
const gameRow = (g: GameMeta, status: string, sort: number) =>
  `  (${q(g.id)}, ${q(g.world)}, ${q(g.name)}, ${q(status)}, ${q(g.phase)}, ${q(g.engine)}, ${q(g.scoring)}, ${g.unique}, ${g.minTimeMs}, ${sort})`;
out.push("insert into public.games (id, world_id, name, status, phase, engine, scoring, is_unique, min_time_ms, sort) values");
out.push(
  [...GAMES.map((g, i) => gameRow(g, "live", i)), ...RETIRED_GAMES.map((g, i) => gameRow(g, "retired", GAMES.length + i))].join(",\n") +
    "\non conflict (id) do update set world_id = excluded.world_id, name = excluded.name, status = excluded.status, phase = excluded.phase, engine = excluded.engine, scoring = excluded.scoring, is_unique = excluded.is_unique, min_time_ms = excluded.min_time_ms, sort = excluded.sort;",
);

// Lab games (hidden from players unless "features.labGames" has them): status coming_soon. A row already there keeps
// its status (a lab game made live by hand, or one brought back from retirement, which a migration moves), so a
// re-seed never hides a live game.
for (const [i, g] of LAB_GAMES.entries()) {
  out.push("insert into public.games (id, world_id, name, status, phase, engine, scoring, is_unique, min_time_ms, sort) values");
  out.push(
    `  (${q(g.id)}, ${q(g.world)}, ${q(g.name)}, 'coming_soon', ${q(g.phase)}, ${q(g.engine)}, ${q(g.scoring)}, ${g.unique}, ${g.minTimeMs}, ${GAMES.length + RETIRED_GAMES.length + i})\non conflict (id) do nothing;`,
  );
}

out.push("insert into public.badges (id, family, tier, name, description, secret, sparks, rule, sort) values");
out.push(
  BADGES.map(
    (b, i) =>
      `  (${q(b.id)}, ${q(b.family)}, ${q(b.tier)}, ${q(b.name)}, ${q(b.description)}, ${!!b.secret}, ${b.sparks}, ${j({ ...b.rule, icon: b.icon })}, ${i})`,
  ).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, description = excluded.description, sparks = excluded.sparks, rule = excluded.rule, sort = excluded.sort;",
);

out.push("insert into public.quests (id, kind, title, goal, xp, sparks, step) values");
out.push(
  [...DAILY_POOL, ...WEEKLY_CHAIN]
    .map((x) => `  (${q(x.id)}, ${q(x.kind)}, ${q(x.title)}, ${j(x.goal)}, ${x.xp}, ${x.sparks}, ${x.step ?? "null"})`)
    .join(",\n") +
    "\non conflict (id) do update set title = excluded.title, goal = excluded.goal, xp = excluded.xp, sparks = excluded.sparks, step = excluded.step;",
);

out.push("insert into public.cosmetics (id, type, name, price_sparks, rarity, payload, unlock_level, sort) values");
out.push(
  COSMETICS.map(
    (c, i) => `  (${q(c.id)}, ${q(c.type)}, ${q(c.name)}, ${c.price}, ${q(c.rarity)}, ${j(c.payload)}, ${c.unlockLevel ?? "null"}, ${i})`,
  ).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, price_sparks = excluded.price_sparks, rarity = excluded.rarity, payload = excluded.payload, unlock_level = excluded.unlock_level, sort = excluded.sort;",
);

const flags = [
  ["duels", true],
  ["party", true],
  ["board_bay_live", true],
  ["crews", true],
  ["music", true],
  ["maintenance", false],
  ["practice_bot", true],
] as const;
out.push("insert into public.feature_flags (key, enabled) values");
out.push(flags.map(([k, v]) => `  (${q(k)}, ${v})`).join(",\n") + "\non conflict (key) do nothing;");
out.push("commit;");

fs.writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
console.log(
  `seed.sql: ${ALL_WORLDS.length} worlds (${WORLDS.length} with live games), ${GAMES.length} live games, ${RETIRED_GAMES.length} retired, ${LAB_GAMES.length} lab, ${BADGES.length} badges, ${DAILY_POOL.length + WEEKLY_CHAIN.length} quests, ${COSMETICS.length} cosmetics`,
);
